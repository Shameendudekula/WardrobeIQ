import mongoose from "mongoose";

export const ITEM_ROLES = ["top", "bottom", "one-piece", "outerwear", "footwear", "accessory", "other"];
export const WEATHER_SUITABILITY = ["suitable", "partly-suitable", "unsuitable", "unknown"];
export const FEEDBACK_TAGS = ["too-formal", "too-casual", "uncomfortable", "great-colors", "not-my-style", "wrong-weather", "love-it"];

// An outfit recommended by the AI stylist. Every item references a real WardrobeItem owned by the user.
const outfitSchema = new mongoose.Schema({
  userId: { type: mongoose.Schema.Types.ObjectId, ref: "User", required: true },
  requestId: { type: String, required: true }, // groups outfits generated by one request
  parentId: { type: mongoose.Schema.Types.ObjectId, ref: "Outfit" }, // set when regenerated from another outfit

  request: {
    prompt: { type: String, maxlength: 500 },
    occasion: String,
    date: String,
    instruction: { type: String, maxlength: 300 } // regeneration instruction
  },
  weather: { type: mongoose.Schema.Types.Mixed }, // snapshot of the weather given to the model
  source: {
    provider: String,
    model: String
  },

  title: String,
  description: String,
  style: String,
  occasion: String,
  formality: String,
  weatherSuitability: { type: String, enum: WEATHER_SUITABILITY },
  colorNotes: String,
  weatherNotes: String,
  preferenceNotes: String,
  explanation: String,
  tips: [String],
  items: [{
    _id: false,
    item: { type: mongoose.Schema.Types.ObjectId, ref: "WardrobeItem", required: true },
    role: { type: String, enum: ITEM_ROLES },
    reason: String
  }],

  saved: { type: Boolean, default: false },
  feedback: {
    rating: { type: String, enum: ["like", "dislike", null] },
    tags: [{ type: String, enum: FEEDBACK_TAGS }],
    comment: { type: String, maxlength: 300 },
    updatedAt: Date
  },
  createdAt: { type: Date, default: Date.now }
});

outfitSchema.index({ userId: 1, createdAt: -1 });
outfitSchema.index({ userId: 1, saved: 1, createdAt: -1 });

export default mongoose.model("Outfit", outfitSchema);
